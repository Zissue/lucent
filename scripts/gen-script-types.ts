const fail = (message: string): never => {
  throw new TypesgenError(message);
};

const parseCliOptions = (
  args: ReadonlyArray<string>,
  repoRoot: string,
): CliOptions => {
  let source = DEFAULT_SOURCE_FILE;
  let out = DEFAULT_OUTPUT_FILE;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index] ?? fail(`Unable to read argument at ${index}`);
    if (arg === "--") {
      continue;
    }
    if (arg === "--source") {
      source = args[index + 1] ?? fail("--source requires a path");
      index += 1;
      continue;
    }
    if (arg.startsWith("--source=")) {
      source = arg.slice("--source=".length);
      continue;
    }
    if (arg === "--out") {
      out = args[index + 1] ?? fail("--out requires a path");
      index += 1;
      continue;
    }
    if (arg.startsWith("--out=")) {
      out = arg.slice("--out=".length);
      continue;
    }
    fail(`Unknown argument: ${arg}`);
  }

  return {
    repoRoot,
    sourceFile: isAbsolute(source) ? source : resolve(repoRoot, source),
    outputFile: isAbsolute(out) ? out : resolve(repoRoot, out),
  };
};

const createProgram = (repoRoot: string): ts.Program => {
  const configPath = resolve(repoRoot, APP_TSCONFIG);
  const readResult = ts.readConfigFile(configPath, ts.sys.readFile);
  if (readResult.error) {
    fail(ts.flattenDiagnosticMessageText(readResult.error.messageText, "\n"));
  }

  const parsed = ts.parseJsonConfigFileContent(
    readResult.config,
    ts.sys,
    dirname(configPath),
  );

  if (parsed.errors.length > 0) {
    fail(
      parsed.errors
        .map((error) =>
          ts.flattenDiagnosticMessageText(error.messageText, "\n"),
        )
        .join("\n"),
    );
  }

  return ts.createProgram({
    rootNames: parsed.fileNames,
    options: parsed.options,
  });
};

const typeParameterText = (
  sourceFile: ts.SourceFile,
  typeParameters: ts.NodeArray<ts.TypeParameterDeclaration> | undefined,
): string =>
  typeParameters === undefined || typeParameters.length === 0
    ? ""
    : `<${typeParameters.map((parameter) => parameter.getText(sourceFile)).join(", ")}>`;

const formatType = (
  checker: ts.TypeChecker,
  node: ts.TypeNode | undefined,
): string => {
  if (node === undefined) {
    return "unknown";
  }

  const text = checker.typeToString(
    checker.getTypeAtLocation(node),
    node,
    ts.TypeFormatFlags.NoTruncation |
      ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType,
  );
  return normalizeTypeText(text);
};

const formatExpandedType = (
  checker: ts.TypeChecker,
  node: ts.TypeNode,
): string =>
  normalizeTypeText(
    checker.typeToString(
      checker.getTypeAtLocation(node),
      node,
      ts.TypeFormatFlags.NoTruncation |
        ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType |
        ts.TypeFormatFlags.InTypeAlias,
    ),
  );

const typeNodeText = (node: ts.TypeNode, sourceFile: ts.SourceFile): string =>
  normalizeTypeText(node.getText(sourceFile));

const transformTypeText = (type: string): string => {
  let output = type;

  output = output.replace(/\bEffect\.Effect\s*</g, "Effect<");
  output = output.replace(/\bOption\.Option\s*</g, "Option<");
  output = output.replace(/\bScope\.Scope\b/g, "Scope");
  output = output.replace(/\bDuration\.Input\b/g, "DurationInput");
  output = output.replace(/\bDuration\.Duration\b/g, "ScriptDuration");
  output = output.replace(/\bReadonlyArray\s*</g, "readonly ");
  output = output.replace(
    /\bBridgeTypes\.InventoryItemSelector\b/g,
    "ObjectSelector<InventoryItemSelectorShape>",
  );
  output = output.replace(
    /\bBridgeTypes\.MonsterSelector\b/g,
    "ObjectSelector<MonsterSelectorShape>",
  );
  output = output.replace(
    /\bBridgeTypes\.ShopItemSelector\b/g,
    "ObjectSelector<ShopItemSelectorShape>",
  );
  output = output.replace(/\bSchema\.Schema\.Type<[^>]+>/g, "unknown");
  output = output.replace(
    /\bData\.TaggedError\([^)]*\)<([^>]*)>/g,
    "Error & $1",
  );

  return output;
};

const normalizeTypeText = (type: string): string =>
  transformTypeText(type)
    .replace(/import\([^)]*\)\./g, "")
    .replace(/\s+/g, " ")
    .trim();

const unwrapEffectReturn = (
  checker: ts.TypeChecker,
  node: ts.TypeNode | undefined,
): string | null => {
  const sourceFile = node?.getSourceFile();
  const reference = parseTypeReference(node);
  if (reference && sourceFile) {
    const args = reference.args.map((arg) => typeNodeText(arg, sourceFile));
    switch (reference.unqualifiedName) {
      case "Effect":
        return `Effect<${args[0] ?? "unknown"}, ${args[1] ?? "never"}${
          args[2] === undefined || args[2] === "never" ? "" : `, ${args[2]}`
        }>`;
      case "BridgeEffect":
        return `Effect<${args[0] ?? "unknown"}, BridgeError>`;
      case "ArmyEffect":
        return `Effect<${args[0] ?? "unknown"}, ${args[1] ?? "never"} | ArmyError | BridgeError>`;
      case "ScriptRecipeEffect":
        return `Effect<${args[0] ?? "unknown"}, unknown>`;
    }
  }

  const formatted = formatType(checker, node);
  if (formatted.startsWith("Effect<")) {
    return formatted;
  }
  return null;
};

const returnTypeText = (
  checker: ts.TypeChecker,
  node: ts.TypeNode | undefined,
): string => unwrapEffectReturn(checker, node) ?? formatType(checker, node);

const getJsDocText = (node: ts.Node): string => {
  const docs = (node as ts.Node & { jsDoc?: ts.JSDoc[] }).jsDoc;
  return docs?.at(-1)?.getText(node.getSourceFile()).trim() ?? "";
};

const isInternalNode = (node: ts.Node): boolean =>
  ts
    .getJSDocTags(node)
    .some((tag) => tag.tagName.text.toLowerCase() === "internal");

const parameterText = (
  checker: ts.TypeChecker,
  parameter: ts.ParameterDeclaration,
): string => {
  const sourceFile = parameter.getSourceFile();
  const name = parameter.name.getText(sourceFile);
  const rest = parameter.dotDotDotToken === undefined ? "" : "...";
  const optional =
    parameter.dotDotDotToken !== undefined ||
    (parameter.questionToken === undefined &&
      parameter.initializer === undefined)
      ? ""
      : "?";
  const documentation = getJsDocText(parameter).replace(/\s+/g, " ");
  return `${documentation === "" ? "" : `${documentation} `}${rest}${name}${optional}: ${formatType(checker, parameter.type)}`;
};

const getJsDocComment = (node: ts.Node): string => {
  const documentation = getJsDocText(node);
  if (documentation === "") {
    return "";
  }
  return `${documentation
    .split("\n")
    .map((line) => `  ${line.trimStart()}`)
    .join("\n")}\n`;
};

const isDeclaration = (node: ts.Node): node is Declaration =>
  ts.isInterfaceDeclaration(node) ||
  ts.isTypeAliasDeclaration(node) ||
  ts.isClassDeclaration(node) ||
  ts.isEnumDeclaration(node);

const isProjectDeclaration = (declaration: Declaration): boolean => {
  const fileName = declaration.getSourceFile().fileName.replaceAll("\\", "/");
  return (
    !fileName.includes("/node_modules/") &&
    !fileName.includes("/.repos/") &&
    !fileName.endsWith(".test.ts")
  );
};

const symbolDeclaration = (
  checker: ts.TypeChecker,
  symbol: ts.Symbol | undefined,
): { readonly declaration: Declaration; readonly symbol: ts.Symbol } | null => {
  if (symbol === undefined) {
    return null;
  }

  const target =
    (symbol.flags & ts.SymbolFlags.Alias) === 0
      ? symbol
      : checker.getAliasedSymbol(symbol);
  const declaration = target.declarations?.find(
    (candidate): candidate is Declaration =>
      isDeclaration(candidate) && isProjectDeclaration(candidate),
  );
  return declaration === undefined ? null : { declaration, symbol: target };
};

const buildDeclarationMap = (
  program: ts.Program,
  sourceFile: ts.SourceFile,
): ReadonlyMap<string, Declaration> => {
  const checker = program.getTypeChecker();
  const declarations = new Map<string, Declaration>();
  const symbols = new Map<string, ts.Symbol>();
  const pending: Declaration[] = [];
  const visited = new Set<Declaration>();

  const addDeclaration = (
    declaration: Declaration,
    symbol: ts.Symbol | undefined,
  ): void => {
    const name = declaration.name?.text;
    if (
      name === undefined ||
      BUILTIN_TYPE_NAMES.has(name) ||
      SUPPORT_TYPE_NAMES.has(name)
    ) {
      return;
    }

    const current = declarations.get(name);
    const currentSymbol = symbols.get(name);
    if (
      current !== undefined &&
      current !== declaration &&
      currentSymbol !== symbol
    ) {
      fail(
        `Public scripting types contain two declarations named ${name}: ${
          current.getSourceFile().fileName
        } and ${declaration.getSourceFile().fileName}`,
      );
    }
    if (current !== undefined) {
      return;
    }

    declarations.set(name, declaration);
    if (symbol !== undefined) {
      symbols.set(name, symbol);
    }
    pending.push(declaration);
  };

  const addSymbolAt = (node: ts.Node): void => {
    const resolved = symbolDeclaration(
      checker,
      checker.getSymbolAtLocation(node),
    );
    if (resolved !== null) {
      addDeclaration(resolved.declaration, resolved.symbol);
    }
  };

  const visitTypeSyntax = (node: ts.Node): void => {
    if (ts.isTypeReferenceNode(node)) {
      addSymbolAt(node.typeName);
    } else if (ts.isExpressionWithTypeArguments(node)) {
      addSymbolAt(node.expression);
    } else if (ts.isImportTypeNode(node) && node.qualifier !== undefined) {
      addSymbolAt(node.qualifier);
    }
    ts.forEachChild(node, visitTypeSyntax);
  };

  const isVisibleClassMember = (member: ts.ClassElement): boolean => {
    if (isInternalNode(member)) return false;
    const modifiers = ts.canHaveModifiers(member)
      ? ts.getModifiers(member)
      : undefined;
    return !modifiers?.some(
      (modifier) =>
        modifier.kind === ts.SyntaxKind.PrivateKeyword ||
        modifier.kind === ts.SyntaxKind.ProtectedKeyword ||
        modifier.kind === ts.SyntaxKind.StaticKeyword,
    );
  };

  const visitDeclarationTypes = (declaration: Declaration): void => {
    if (ts.isInterfaceDeclaration(declaration)) {
      for (const typeParameter of declaration.typeParameters ?? []) {
        visitTypeSyntax(typeParameter);
      }
      for (const clause of declaration.heritageClauses ?? []) {
        visitTypeSyntax(clause);
      }
      for (const member of declaration.members) {
        if (!isInternalNode(member)) visitTypeSyntax(member);
      }
      return;
    }

    if (ts.isTypeAliasDeclaration(declaration)) {
      ts.forEachChild(declaration, visitTypeSyntax);
      return;
    }

    if (!ts.isClassDeclaration(declaration)) {
      return;
    }

    for (const typeParameter of declaration.typeParameters ?? []) {
      visitTypeSyntax(typeParameter);
    }
    for (const clause of declaration.heritageClauses ?? []) {
      visitTypeSyntax(clause);
    }
    for (const member of declaration.members) {
      if (!isVisibleClassMember(member)) {
        continue;
      }
      if (
        ts.isPropertyDeclaration(member) ||
        ts.isGetAccessorDeclaration(member) ||
        ts.isSetAccessorDeclaration(member) ||
        ts.isMethodDeclaration(member)
      ) {
        if (member.type !== undefined) {
          visitTypeSyntax(member.type);
        }
      }
      if (
        ts.isMethodDeclaration(member) ||
        ts.isGetAccessorDeclaration(member) ||
        ts.isSetAccessorDeclaration(member)
      ) {
        for (const typeParameter of member.typeParameters ?? []) {
          visitTypeSyntax(typeParameter);
        }
        for (const parameter of member.parameters) {
          visitTypeSyntax(parameter);
        }
      }
    }
  };

  for (const rootName of SCRIPT_API_ROOT_INTERFACES) {
    const declaration =
      sourceFile.statements.find(
        (statement): statement is ts.InterfaceDeclaration =>
          ts.isInterfaceDeclaration(statement) &&
          statement.name.text === rootName,
      ) ?? fail(`Unable to find interface ${rootName}`);
    addDeclaration(
      declaration,
      checker.getSymbolAtLocation(declaration.name),
    );
  }

  for (let index = 0; index < pending.length; index += 1) {
    const declaration = pending[index];
    if (declaration === undefined || visited.has(declaration)) {
      continue;
    }
    visited.add(declaration);
    visitDeclarationTypes(declaration);
  }

  return declarations;
};

const getInterface = (
  declarations: ReadonlyMap<string, Declaration>,
  name: string,
  seen = new Set<string>(),
): ts.InterfaceDeclaration => {
  if (seen.has(name)) {
    fail(`Unable to resolve circular interface alias ${name}`);
  }

  const declaration =
    declarations.get(name) ?? fail(`Unable to find interface ${name}`);

  if (ts.isInterfaceDeclaration(declaration)) {
    return declaration;
  }

  if (ts.isTypeAliasDeclaration(declaration)) {
    const reference = parseTypeReference(declaration.type);
    if (reference) {
      const nextSeen = new Set(seen);
      nextSeen.add(name);
      const omitted = resolveOmitInterfaceAlias(
        reference,
        (targetName) => getInterface(declarations, targetName, nextSeen),
        { referenceName: "unqualifiedName" },
      );
      if (omitted) {
        return omitted;
      }
      return getInterface(declarations, reference.unqualifiedName, nextSeen);
    }
  }

  return fail(`Unable to find interface ${name}`);
};

const getDeclaration = (
  declarations: ReadonlyMap<string, Declaration>,
  name: string,
): Declaration | null => declarations.get(name) ?? null;

const parseEffectValueShape = (
  node: ts.TypeNode | undefined,
): string | null => {
  const reference = parseTypeReference(node);
  if (
    !reference ||
    reference.unqualifiedName !== "EffectValue" ||
    reference.args.length !== 1
  ) {
    return null;
  }

  const target = parseTypeReference(reference.args[0]);
  return target?.unqualifiedName ?? null;
};

const interfaceNameForProperty = (propertyName: string): string => {
  const normalized = propertyName
    .replace(/(^|[-_\s]+)([a-zA-Z0-9])/g, (_match, _separator, char: string) =>
      char.toUpperCase(),
    )
    .replace(/[^A-Za-z0-9_$]/g, "");
  return `${normalized}Api`;
};

const nestedInterfaceName = (
  parentName: string,
  propertyName: string,
): string =>
  `${parentName.replace(/Api$/, "")}${interfaceNameForProperty(propertyName)}`;

const collectTypeNames = (text: string, output: Set<string>): void => {
  const typeText = text
    .replaceAll(/\/\*\*[\s\S]*?\*\//g, "")
    .replaceAll(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g, "");
  for (const match of typeText.matchAll(
    /\b[A-Za-z_$][A-Za-z0-9_$]*\b/g,
  )) {
    const token = match[0];
    if (!BUILTIN_TYPE_NAMES.has(token) && /^[A-Z]/.test(token)) {
      output.add(token);
    }
  }
};

const renderMethodSignature = (
  checker: ts.TypeChecker,
  node: ts.MethodSignature | ts.FunctionTypeNode,
  name: string,
): string => {
  const sourceFile = node.getSourceFile();
  const typeParameters = typeParameterText(sourceFile, node.typeParameters);
  const parameters = node.parameters
    .map((parameter) => parameterText(checker, parameter))
    .join(", ");
  return `${name}${typeParameters}(${parameters}): ${returnTypeText(checker, node.type)};`;
};

const renderCallSignature = (
  checker: ts.TypeChecker,
  node: ts.CallSignatureDeclaration,
): string => {
  const sourceFile = node.getSourceFile();
  const typeParameters = typeParameterText(sourceFile, node.typeParameters);
  const parameters = node.parameters
    .map((parameter) => parameterText(checker, parameter))
    .join(", ");
  return `${typeParameters}(${parameters}): ${returnTypeText(checker, node.type)};`;
};

const renderConstructSignature = (
  checker: ts.TypeChecker,
  node: ts.ConstructSignatureDeclaration,
): string => {
  const sourceFile = node.getSourceFile();
  const typeParameters = typeParameterText(sourceFile, node.typeParameters);
  const parameters = node.parameters
    .map((parameter) => parameterText(checker, parameter))
    .join(", ");
  return `new ${typeParameters}(${parameters}): ${returnTypeText(checker, node.type)};`;
};

type RenderState = {
  readonly checker: ts.TypeChecker;
  readonly declarations: ReadonlyMap<string, Declaration>;
  readonly rendered: Map<string, RenderedInterface>;
  readonly referencedTypes: Set<string>;
};

const renderInterfaceFromDeclaration = (
  state: RenderState,
  declaration: ts.InterfaceDeclaration,
  outputName: string,
): string => {
  const lines: string[] = [`interface ${outputName} {`];

  for (const member of declaration.members) {
    if (isInternalNode(member)) continue;

    if (ts.isConstructSignatureDeclaration(member)) {
      const signature = renderConstructSignature(state.checker, member);
      collectTypeNames(signature, state.referencedTypes);
      lines.push(`${getJsDocComment(member)}    ${signature}`);
      continue;
    }

    if (ts.isCallSignatureDeclaration(member)) {
      const signature = renderCallSignature(state.checker, member);
      collectTypeNames(signature, state.referencedTypes);
      lines.push(`${getJsDocComment(member)}    ${signature}`);
      continue;
    }

    if (ts.isMethodSignature(member)) {
      const name = getPropertyName(member.name);
      if (name === null) {
        continue;
      }
      const signature = renderMethodSignature(state.checker, member, name);
      collectTypeNames(signature, state.referencedTypes);
      lines.push(`${getJsDocComment(member)}    ${signature}`);
      continue;
    }

    if (!ts.isPropertySignature(member)) {
      continue;
    }

    const name = getPropertyName(member.name);
    if (name === null) {
      continue;
    }

    if (member.type && ts.isFunctionTypeNode(member.type)) {
      const signature = renderMethodSignature(state.checker, member.type, name);
      collectTypeNames(signature, state.referencedTypes);
      lines.push(`${getJsDocComment(member)}    ${signature}`);
      continue;
    }

    const shapeName = parseEffectValueShape(member.type);
    if (shapeName !== null) {
      const childOutputName =
        outputName === "ScriptApi"
          ? interfaceNameForProperty(name)
          : nestedInterfaceName(outputName, name);
      renderApiInterface(state, shapeName, childOutputName);
      lines.push(`    readonly ${name}: ${childOutputName};`);
      continue;
    }

    const reference = parseTypeReference(member.type);
    if (reference !== null && SUPPORT_TYPE_NAMES.has(reference.unqualifiedName)) {
      const readonly = member.modifiers?.some(
        (modifier) => modifier.kind === ts.SyntaxKind.ReadonlyKeyword,
      )
        ? "readonly "
        : "";
      const optional = member.questionToken === undefined ? "" : "?";
      lines.push(
        `${getJsDocComment(member)}    ${readonly}${name}${optional}: ${formatType(
          state.checker,
          member.type,
        )};`,
      );
      continue;
    }

    const childDeclaration =
      reference === null
        ? null
        : getDeclaration(state.declarations, reference.unqualifiedName);
    if (childDeclaration && ts.isInterfaceDeclaration(childDeclaration)) {
      const childOutputName = childDeclaration.name.text;
      renderApiInterface(state, childDeclaration.name.text, childOutputName);
      lines.push(
        `${getJsDocComment(member)}    readonly ${name}: ${childOutputName};`,
      );
      continue;
    }

    const readonly = member.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ReadonlyKeyword,
    )
      ? "readonly "
      : "";
    const optional = member.questionToken === undefined ? "" : "?";
    const type = formatType(state.checker, member.type);
    collectTypeNames(type, state.referencedTypes);
    lines.push(
      `${getJsDocComment(member)}    ${readonly}${name}${optional}: ${type};`,
    );
  }

  lines.push("}");
  return lines.join("\n");
};

const renderApiInterface = (
  state: RenderState,
  sourceName: string,
  outputName: string,
): void => {
  if (state.rendered.has(outputName)) {
    return;
  }

  const declaration = getInterface(state.declarations, sourceName);
  state.rendered.set(outputName, {
    name: outputName,
    content: renderInterfaceFromDeclaration(state, declaration, outputName),
  });
};

const stripDeclarationText = (text: string): string =>
  transformTypeText(text)
    .replace(/^export\s+/gm, "")
    .replace(/^declare\s+/gm, "")
    .replace(/\bprivate\s+/g, "")
    .replace(/\bprotected\s+/g, "")
    .replace(/#private;\n?/g, "")
    .replace(/import\([^)]*\)\./g, "")
    .replace(/Schema\.Literals<[^;]+;/g, "unknown;");

const isSimpleHeritageExpression = (expression: ts.Expression): boolean =>
  ts.isIdentifier(expression) ||
  (ts.isPropertyAccessExpression(expression) &&
    isSimpleHeritageExpression(expression.expression));

const renderClassAsInterface = (
  checker: ts.TypeChecker,
  declaration: ts.ClassDeclaration,
): string => {
  const name = declaration.name?.text ?? fail("Cannot render anonymous class");
  const sourceFile = declaration.getSourceFile();
  const typeParameters = typeParameterText(
    sourceFile,
    declaration.typeParameters,
  );
  const extendsClause = declaration.heritageClauses
    ?.flatMap((clause) =>
      clause.token === ts.SyntaxKind.ExtendsKeyword
        ? clause.types
            .filter((type) => isSimpleHeritageExpression(type.expression))
            .map((type) => type.getText(type.getSourceFile()))
        : [],
    )
    .at(0);
  const lines = [
    `interface ${name}${typeParameters}${extendsClause ? ` extends ${extendsClause}` : ""} {`,
  ];

  for (const member of declaration.members) {
    if (isInternalNode(member)) continue;

    const modifiers = ts.canHaveModifiers(member)
      ? ts.getModifiers(member)
      : undefined;
    if (
      modifiers?.some(
        (modifier) =>
          modifier.kind === ts.SyntaxKind.PrivateKeyword ||
          modifier.kind === ts.SyntaxKind.ProtectedKeyword ||
          modifier.kind === ts.SyntaxKind.StaticKeyword,
      )
    ) {
      continue;
    }

    if (ts.isGetAccessorDeclaration(member)) {
      const propertyName = getPropertyName(member.name);
      if (propertyName === null) continue;
      lines.push(
        `  readonly ${propertyName}: ${returnTypeText(checker, member.type)};`,
      );
      continue;
    }

    if (ts.isPropertyDeclaration(member)) {
      const propertyName = getPropertyName(member.name);
      if (propertyName === null) continue;
      const optional = member.questionToken === undefined ? "" : "?";
      lines.push(
        `  ${propertyName}${optional}: ${formatType(checker, member.type)};`,
      );
      continue;
    }

    if (ts.isMethodDeclaration(member)) {
      const methodName = getPropertyName(member.name);
      if (methodName === null) continue;
      const sourceFile = member.getSourceFile();
      const typeParameters = typeParameterText(
        sourceFile,
        member.typeParameters,
      );
      const parameters = member.parameters
        .map((parameter) => parameterText(checker, parameter))
        .join(", ");
      lines.push(
        `  ${methodName}${typeParameters}(${parameters}): ${returnTypeText(checker, member.type)};`,
      );
    }
  }

  lines.push("}");
  return lines.join("\n");
};

const isSchemaTypeAlias = (declaration: ts.TypeAliasDeclaration): boolean => {
  const reference = parseTypeReference(declaration.type);
  return reference?.name === "Schema.Schema.Type";
};

const renderTypeAlias = (
  checker: ts.TypeChecker,
  declaration: ts.TypeAliasDeclaration,
): string => {
  const documentation = getJsDocText(declaration);
  const typeParameters = typeParameterText(
    declaration.getSourceFile(),
    declaration.typeParameters,
  );
  const raw = stripDeclarationText(
    declaration.getText(declaration.getSourceFile()),
  );
  const rendered =
    !isSchemaTypeAlias(declaration) && !raw.includes("typeof ")
      ? raw
      : `type ${declaration.name.text}${typeParameters} = ${formatExpandedType(
          checker,
          declaration.type,
        )};`;
  return documentation === "" ? rendered : `${documentation}\n${rendered}`;
};

const declarationText = (
  checker: ts.TypeChecker,
  declaration: Declaration,
): string | null => {
  const sourceFile = declaration.getSourceFile();
  const name = declaration.name?.text;
  if (
    name === "ScriptExecutionError" ||
    name === "ScriptNotReadyError" ||
    name === "ScriptStopSignal"
  ) {
    return null;
  }

  if (ts.isClassDeclaration(declaration)) {
    return renderClassAsInterface(checker, declaration);
  }

  if (ts.isTypeAliasDeclaration(declaration)) {
    return renderTypeAlias(checker, declaration);
  }

  if (ts.isEnumDeclaration(declaration)) {
    return stripDeclarationText(declaration.getText(sourceFile)).replace(
      /^enum\s+/,
      "declare enum ",
    );
  }

  return stripDeclarationText(declaration.getText(sourceFile));
};

const renderReferencedDeclarations = (
  state: RenderState,
  apiInterfaceNames: ReadonlySet<string>,
): readonly string[] => {
  const output: string[] = [];
  const seen = new Set([...apiInterfaceNames, ...SUPPORT_TYPE_NAMES]);
  for (const declaration of state.declarations.values()) {
    const visit = (node: ts.Node): void => {
      if (ts.isTypeParameterDeclaration(node)) {
        seen.add(node.name.text);
      }
      ts.forEachChild(node, visit);
    };
    visit(declaration);
  }
  const pending = Array.from(state.referencedTypes).sort();

  for (let index = 0; index < pending.length; index += 1) {
    const name = pending[index];
    if (!name || seen.has(name) || BUILTIN_TYPE_NAMES.has(name)) {
      continue;
    }
    seen.add(name);

    const declaration =
      state.declarations.get(name) ??
      fail(`Unable to resolve public scripting type ${name}`);

    const rendered = declarationText(state.checker, declaration);
    if (rendered === null) {
      continue;
    }
    const text = rendered;
    output.push(text);
    collectTypeNames(text, state.referencedTypes);
    for (const referenced of Array.from(state.referencedTypes)) {
      if (!seen.has(referenced) && !pending.includes(referenced)) {
        pending.push(referenced);
      }
    }
  }

  return output;
};

// Use the installed Effect overloads without exposing the rest of its module.
const renderEffectPipeable = (compilerOptions: ts.CompilerOptions): string => {
  const resolvedModule =
    ts.resolveModuleName(
      "effect/Pipeable",
      fileURLToPath(import.meta.url),
      compilerOptions,
      ts.sys,
    ).resolvedModule ??
    fail("Unable to resolve the installed effect/Pipeable module");
  const source =
    ts.sys.readFile(resolvedModule.resolvedFileName) ??
    fail("Unable to read the installed effect/Pipeable module");
  const sourceFile = ts.createSourceFile(
    resolvedModule.resolvedFileName,
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  const declaration =
    sourceFile.statements.find(
      (statement): statement is ts.InterfaceDeclaration =>
        ts.isInterfaceDeclaration(statement) &&
        statement.name.text === "Pipeable",
    ) ?? fail("Unable to find the installed Effect Pipeable interface");
  const members = declaration.members.map(
    (member) => `  ${member.getText(sourceFile)}`,
  );
  return `interface ScriptEffectPipeable {\n${members.join("\n")}\n}`;
};

const renderScriptTypes = (
  program: ts.Program,
  declarations: ReadonlyMap<string, Declaration>,
  schemaDeclarations: string,
): string => {
  const checker = program.getTypeChecker();
  const state: RenderState = {
    checker,
    declarations,
    rendered: new Map(),
    referencedTypes: new Set(),
  };

  for (const rootName of SCRIPT_API_ROOT_INTERFACES) {
    renderApiInterface(state, rootName, rootName);
  }

  const interfaceNames = new Set(state.rendered.keys());
  const referencedDeclarations = renderReferencedDeclarations(
    state,
    interfaceNames,
  );
  const rootInterfaceOrder = new Map<string, number>(
    SCRIPT_API_ROOT_INTERFACES.map((name, index) => [name, index]),
  );
  const interfaces = Array.from(state.rendered.values())
    .sort((left, right) => {
      const leftOrder = rootInterfaceOrder.get(left.name);
      const rightOrder = rootInterfaceOrder.get(right.name);
      if (leftOrder !== undefined || rightOrder !== undefined) {
        return (
          (leftOrder ?? Number.POSITIVE_INFINITY) -
          (rightOrder ?? Number.POSITIVE_INFINITY)
        );
      }
      return left.name.localeCompare(right.name);
    })
    .map((entry) => entry.content);

  const lines = [
    GENERATED_HEADER,
    "",
    "/* eslint-disable */",
    "",
    SUPPORT_DECLARATIONS.trimEnd(),
    schemaDeclarations,
    "",
    "type ScriptMain = () => Generator<Effect<any, any, never>, unknown, any>;",
    "",
    ...interfaces,
    "",
    renderEffectPipeable(program.getCompilerOptions()),
    "",
    ...referencedDeclarations,
    "",
  ];

  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
};

