const validateGeneratedTypes = (content: string): void => {
  const sourceFile = ts.createSourceFile(
    "script-api.d.ts",
    content,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const interfaces = new Map<string, ts.InterfaceDeclaration>();
  const typeAliases = new Map<string, ts.TypeAliasDeclaration>();

  for (const specifier of [
    "effect",
    "lucent/api",
    "lucent/autorelogin",
    "lucent/autozone",
    "lucent/filesystem",
    "lucent/http",
    "lucent/schema",
    "lucent/script",
  ]) {
    if (!content.includes(`declare module "${specifier}"`)) {
      fail(`Generated scripting types must declare ${specifier}`);
    }
  }
  if (content.includes('declare module "lucent"')) {
    fail("Generated scripting types must not declare the removed lucent module");
  }
  if (content.includes('declare module "@lucent/')) {
    fail("Generated scripting types must not declare removed scoped modules");
  }

  for (const statement of sourceFile.statements) {
    if (ts.isInterfaceDeclaration(statement)) {
      interfaces.set(statement.name.text, statement);
    } else if (ts.isTypeAliasDeclaration(statement)) {
      typeAliases.set(statement.name.text, statement);
    }
  }

  for (const name of [
    "ScriptEventsOn",
    "ScriptPacketOn",
    "ScriptWaitForEvent",
    "ScriptWaitForPacket",
  ]) {
    const declaration = interfaces.get(name);
    if (
      declaration === undefined ||
      !declaration.members.some(ts.isCallSignatureDeclaration)
    ) {
      fail(`Generated ${name} must retain at least one call signature`);
    }
  }

  const interfaceMemberNames = (name: string): readonly string[] => {
    const declaration = interfaces.get(name);
    if (declaration === undefined) {
      return fail(`Generated scripting types must include ${name}`);
    }
    if (declaration.members.some(ts.isIndexSignatureDeclaration)) {
      fail(`Generated ${name} must not expose an open-ended index signature`);
    }
    return declaration.members
      .flatMap((member) => {
        if (!("name" in member) || member.name === undefined) return [];
        const memberName = getPropertyName(member.name);
        return memberName === null ? [] : [memberName];
      })
      .toSorted();
  };

  const expectedEffectMembers = [
    "all",
    "as",
    "asVoid",
    "catch",
    "fail",
    "flatMap",
    "forEach",
    "gen",
    "map",
    "mapError",
    "raceFirst",
    "sleep",
    "succeed",
    "sync",
    "tap",
    "timeoutOption",
    "try",
    "tryPromise",
    "void",
  ];
  const expectedOptionMembers = [
    "getOrElse",
    "isNone",
    "isSome",
    "map",
    "match",
    "none",
    "some",
  ];
  const expectedDurationMembers = [
    "days",
    "hours",
    "millis",
    "minutes",
    "seconds",
    "toMillis",
  ];
  for (const [name, expected] of [
    ["ScriptEffectModule", expectedEffectMembers],
    ["ScriptOptionModule", expectedOptionMembers],
    ["ScriptDurationModule", expectedDurationMembers],
  ] as const) {
    const actual = interfaceMemberNames(name);
    if (actual.join("\n") !== expected.toSorted().join("\n")) {
      fail(`Generated ${name} does not match its supported member list`);
    }
  }

  for (const [name, hidden] of [
    ["LiveModel", ["replaceFrom", "snapshot", "update"]],
    ["LiveEntity", ["projectAuras", "writeAuraMonsterState"]],
    ["LiveMonster", ["replaceDrops"]],
  ] as const) {
    const members = new Set(interfaceMemberNames(name));
    const leaked = hidden.filter((member) => members.has(member));
    if (leaked.length > 0) {
      fail(`Generated ${name} exposes @internal members: ${leaked.join(", ")}`);
    }
  }

  for (const name of [
    "AuraTiming",
    "AuraApplication",
    "AuraSeed",
    "AuraWithdrawal",
    "PassiveAuraInput",
    "AuraMutation",
    "AuraDelta",
    "ActiveAuraEdit",
    "reduceActiveAura",
  ]) {
    if (new RegExp(`\\b${name}\\b`, "u").test(content)) {
      fail(`Generated scripting types expose internal aura symbol ${name}`);
    }
  }

  const packetForDirection = typeAliases.get("PacketForDirection");
  if (
    packetForDirection === undefined ||
    !packetForDirection.type
      .getText(sourceFile)
      .replace(/\s+/gu, " ")
      .includes("Extract< FlashPacket,")
  ) {
    fail("Generated PacketForDirection must extract from FlashPacket");
  }
  if (content.includes("Scope.Scope")) {
    fail("Generated scripting types must normalize Scope.Scope to Scope");
  }
  if (/\binterface\s+Extract\b/u.test(content)) {
    fail("Generated scripting types must use the built-in Extract type");
  }
  if (/^type Event\s*=/mu.test(content)) {
    fail("Generated scripting types must not shadow the DOM Event type");
  }
  const directSelfAlias =
    /^type ([A-Za-z_$][A-Za-z0-9_$]*)\s*=\s*\1\s*;$/mu.exec(content);
  if (directSelfAlias !== null) {
    fail(`Generated ${directSelfAlias[1]} type must not alias itself`);
  }
  for (const name of ["R", "Json", "State", "Session"]) {
    if (new RegExp(`^interface ${name}\\b`, "mu").test(content)) {
      fail(`Generated scripting types must not contain an opaque ${name}`);
    }
  }

  validateScriptingFixture(content);
};

const main = async (options: CliOptions): Promise<void> => {
  const program = createProgram(options.repoRoot);
  const sourceFile =
    program.getSourceFile(options.sourceFile) ??
    fail(`Unable to load ${relative(options.repoRoot, options.sourceFile)}`);

  const declarations = buildDeclarationMap(program, sourceFile);
  const schemaSource = await fs.readFile(
    join(options.repoRoot, "app/src/renderer/apps/game/scripting/schema/public.ts"),
    "utf8",
  );
  const schemaDeclarations = `declare module "lucent/schema" {\n${schemaSource.replace(/\bdeclare (const|function|class)\b/g, "$1")}\n}`;
  const content = renderScriptTypes(program, declarations, schemaDeclarations);
  validateGeneratedTypes(content);

  await fs.mkdir(dirname(options.outputFile), { recursive: true });
  const current = await fs
    .readFile(options.outputFile, "utf8")
    .catch(() => null);
  if (current !== content) {
    await fs.writeFile(options.outputFile, content, "utf8");
  }

  console.info(
    `Generated scripting types at ${relative(options.repoRoot, options.outputFile)}`,
  );
};

