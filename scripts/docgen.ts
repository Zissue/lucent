const memberCopyCall = (member: MemberDoc): string => {
  const requiredArguments = member.parameters
    .filter((parameter) => parameter.required)
    .map((parameter) =>
      parameter.rest ? `...${parameter.name}` : parameter.name,
    )
    .join(", ");
  const expression =
    member.kind === "method"
      ? `${member.path}(${requiredArguments})`
      : member.path;

  if (member.returnDoc.result !== null) {
    return `yield* ${expression};`;
  }

  return member.kind === "method" ? `${expression};` : expression;
};

const renderMember = (
  lines: string[],
  member: MemberDoc,
  typeLinks: ReadonlyMap<string, TypeLink>,
  renderTypeCodeBlock: TypeCodeBlockRenderer,
  headingName = member.path,
) => {
  lines.push(`<a id="${memberAnchor(member.path)}"></a>`, "");
  lines.push(
    `### \`${headingName}${member.kind === "method" ? "()" : ""}\`${renderHeadingSourceLink(member)}`,
    "",
  );

  const summary = member.summary || GENERATED_MEMBER_SUMMARIES[member.path] || "";
  if (summary !== "") {
    lines.push(summary, "");
  }

  if (member.sourceUrl === null) {
    lines.push(renderSource(member), "");
  }

  lines.push(
    `<div data-api-copy-call="${escapeHtml(memberCopyCall(member))}" hidden></div>`,
    "",
  );
  lines.push(
    renderLinkedTypeCodeBlock(
      member.signature,
      typeLinks,
      renderTypeCodeBlock,
    ),
    "",
  );

  const preview = GENERATED_MEMBER_PREVIEWS[member.path];
  if (preview !== undefined) {
    lines.push(preview, "");
  }

  if (member.parameters.length > 0) {
    lines.push(
      "| Name | Type | Required | Default | Description |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const parameter of member.parameters) {
      lines.push(
        `| ${renderCode(`${parameter.rest ? "..." : ""}${parameter.name}`)} | ${renderTypeExpression(parameter.type, typeLinks)} | ${renderBooleanMark(parameter.required)} | ${parameter.defaultValue === "" ? "" : renderCode(parameter.defaultValue)} | ${escapeTableCell(parameter.description)} |`,
      );
    }
    lines.push("");
  }

  lines.push(
    `**Returns:** ${renderTypeExpression(member.returnDoc.result ?? member.returnDoc.raw, typeLinks)}`,
    "",
  );
  if (member.returnDoc.error !== null) {
    lines.push(
      `**Errors:** ${renderTypeExpression(member.returnDoc.error, typeLinks)}`,
      "",
    );
  }

  for (const example of member.examples) {
    lines.push("#### Example", "", example, "");
  }
};

