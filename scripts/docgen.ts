const getText = (
  value:
    | string
    | ts.NodeArray<ts.JSDocComment>
    | readonly ts.JSDocComment[]
    | undefined,
): string => {
  if (value === undefined) {
    return "";
  }
  if (typeof value === "string") {
    return value.trim();
  }

  return value
    .map((part) => {
      const text = (part as { text?: unknown }).text;
      return text === undefined ? (part as ts.Node).getText() : String(text);
    })
    .join("")
    .trim();
};

