const createProgram = (
  repoRoot: string,
  packages: readonly ScriptPackageReference[],
): ts.Program => {
  const configPath = resolve(repoRoot, APP_TSCONFIG);
  const readResult = ts.readConfigFile(configPath, ts.sys.readFile);
  if (readResult.error) {
    fail(ts.flattenDiagnosticMessageText(readResult.error.messageText, "\n"));
  }

  const parsed = ts.parseJsonConfigFileContent(
    readResult.config,
    ts.sys,
    dirname(configPath),
  );

  if (parsed.errors.length > 0) {
    fail(
      parsed.errors
        .map((error) =>
          ts.flattenDiagnosticMessageText(error.messageText, "\n"),
        )
        .join("\n"),
    );
  }

  return ts.createProgram({
    rootNames: [
      ...parsed.fileNames,
      resolve(repoRoot, "docs/public/script-api.d.ts"),
      ...packages.flatMap((pkg) =>
        pkg.typesFile === undefined ? [] : [pkg.typesFile],
      ),
    ],
    options: {
      ...parsed.options,
      baseUrl: repoRoot,
      paths: DOCGEN_COMPILER_PATHS,
    },
  });
};

