const buildDeclarationMap = (
  program: ts.Program,
  publicEntryPoint: ts.SourceFile,
): ReadonlyMap<string, ts.InterfaceDeclaration | ts.TypeAliasDeclaration> => {
  const checker = program.getTypeChecker();
  const declarations = new Map<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >();

  const declarationRank = (
    declaration: ts.InterfaceDeclaration | ts.TypeAliasDeclaration,
  ): number => {
    const fileName = declaration.getSourceFile().fileName.replaceAll("\\", "/");
    return (
      (fileName.includes("/dist/") ? 10 : 0) +
      (/\.d\.[cm]?ts$/.test(fileName) ? 5 : 0)
    );
  };

  const isExported = (
    declaration: ts.InterfaceDeclaration | ts.TypeAliasDeclaration,
  ): boolean =>
    ts
      .getModifiers(declaration)
      ?.some(
        (modifier) =>
          modifier.kind === ts.SyntaxKind.ExportKeyword ||
          modifier.kind === ts.SyntaxKind.DefaultKeyword,
      ) ?? false;

  const add = (
    declaration: ts.InterfaceDeclaration | ts.TypeAliasDeclaration,
    preferred = false,
  ): void => {
    if (!isDocumentableSourceFile(declaration.getSourceFile())) {
      return;
    }
    const current = declarations.get(declaration.name.text);
    if (
      preferred ||
      current === undefined ||
      declarationRank(declaration) < declarationRank(current)
    ) {
      declarations.set(declaration.name.text, declaration);
    }
  };

  for (const statement of publicEntryPoint.statements) {
    if (
      ts.isInterfaceDeclaration(statement) ||
      ts.isTypeAliasDeclaration(statement)
    ) {
      add(statement, true);
      continue;
    }
    if (
      !ts.isImportDeclaration(statement) ||
      statement.importClause?.namedBindings === undefined ||
      !ts.isNamedImports(statement.importClause.namedBindings)
    ) {
      continue;
    }
    for (const element of statement.importClause.namedBindings.elements) {
      const symbol = checker.getSymbolAtLocation(element.name);
      const target =
        symbol !== undefined && (symbol.flags & ts.SymbolFlags.Alias) !== 0
          ? checker.getAliasedSymbol(symbol)
          : symbol;
      const declaration = target?.declarations?.find(
        (
          candidate,
        ): candidate is ts.InterfaceDeclaration | ts.TypeAliasDeclaration =>
          ts.isInterfaceDeclaration(candidate) ||
          ts.isTypeAliasDeclaration(candidate),
      );
      if (declaration !== undefined) {
        add(declaration, true);
      }
    }
  }

  for (const sourceFile of program.getSourceFiles()) {
    if (!isDocumentableSourceFile(sourceFile)) {
      continue;
    }
    for (const statement of sourceFile.statements) {
      if (
        (ts.isInterfaceDeclaration(statement) ||
          ts.isTypeAliasDeclaration(statement)) &&
        isExported(statement)
      ) {
        add(statement);
      }
    }
  }

  return declarations;
};

const getInterface = (
  declarations: ReadonlyMap<
    string,
    ts.InterfaceDeclaration | ts.TypeAliasDeclaration
  >,
  name: string,
  seen = new Set<string>(),
): ts.InterfaceDeclaration => {
  if (seen.has(name)) {
    fail(`Unable to resolve circular interface alias ${name}`);
  }

  const declaration =
    declarations.get(name) ?? fail(`Unable to find interface ${name}`);

  if (ts.isInterfaceDeclaration(declaration)) {
    return declaration;
  }

  const reference = parseTypeReference(declaration.type);
  if (reference) {
    const nextSeen = new Set(seen);
    nextSeen.add(name);
    const omitted = resolveOmitInterfaceAlias(
      reference,
      (targetName) => getInterface(declarations, targetName, nextSeen),
      { referenceName: "unqualifiedName" },
    );
    if (omitted) {
      return omitted;
    }
    return getInterface(declarations, reference.unqualifiedName, nextSeen);
  }

  return fail(`Unable to find interface ${name}`);
};

