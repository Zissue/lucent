import { promises as fs } from "fs";
import { join } from "path";

import * as Context from "effect/Context";
import * as Effect from "effect/Effect";
import * as Layer from "effect/Layer";
import * as Schema from "effect/Schema";
import { FileSystem } from "effect/FileSystem";

import { DesktopEnvironment } from "../app/DesktopEnvironment";
import { makeAtomicFile } from "../filesystem/AtomicFile";
import { resolveScriptWorkspacePaths } from "./ScriptWorkspacePaths";

const scriptWorkspaceOperationSchema = Schema.Literals([
  "copy-types",
  "create-config",
  "create-directory",
]);

export class ScriptWorkspaceError extends Schema.TaggedError<ScriptWorkspaceError>()(
  "ScriptWorkspaceError",
  {
    operation: scriptWorkspaceOperationSchema,
    path: Schema.String,
    cause: Schema.Defect(),
  },
) {
  override get message(): string {
    return `Script workspace ${this.operation} failed at ${this.path}.`;
  }
}

export interface ScriptWorkspaceShape {
  readonly initialize: Effect.Effect<void, ScriptWorkspaceError>;
}

export class ScriptWorkspace extends Context.Service<
  ScriptWorkspace,
  ScriptWorkspaceShape
>()("lucent/desktop/scripting/ScriptWorkspace") {}

export const SCRIPT_WORKSPACE_CONFIG = `${JSON.stringify(
  {
    compilerOptions: {
      target: "ES2020",
      module: "CommonJS",
      moduleResolution: "Node",
      lib: ["ES2020", "DOM"],
      checkJs: false,
      skipLibCheck: true,
      baseUrl: "./packages",
    },
    include: [
      "script-api.d.ts",
      "scripts/**/*.js",
      "scripts/**/*.cjs",
      "scripts/**/*.d.ts",
      "packages/**/*.js",
      "packages/**/*.cjs",
      "packages/**/*.d.ts",
    ],
  },
  null,
  2,
)}\n`;

const GENERATED_TYPES_PREFIX =
  "// Generated by pnpm run types:scripting. Do not edit directly.";

const makeError = (
  operation: typeof scriptWorkspaceOperationSchema.Type,
  path: string,
  cause: unknown,
) => new ScriptWorkspaceError({ operation, path, cause });

export const layer = Layer.effect(
  ScriptWorkspace,
  Effect.gen(function* () {
    const env = yield* DesktopEnvironment;
    const fileSystem = yield* FileSystem;
    const atomicFile = makeAtomicFile(fileSystem);
    const { dataDir, packagesDir, scriptsDir } = resolveScriptWorkspacePaths(
      env.workspaceDir,
    );
    const configPath = join(env.workspaceDir, "jsconfig.json");
    const typesPath = join(env.workspaceDir, "script-api.d.ts");
    const templatePath = env.isDev
      ? join(env.assetsDir, "..", "docs", "public", "script-api.d.ts")
      : join(env.assetsDir, "..", "script-api.d.ts");

    const createDirectory = (path: string) =>
      Effect.tryPromise({
        try: () => fs.mkdir(path, { recursive: true }),
        catch: (cause) => makeError("create-directory", path, cause),
      }).pipe(Effect.asVoid);

    const createPrivateDirectory = (path: string) =>
      Effect.tryPromise({
        try: async () => {
          await fs.mkdir(path, { mode: 0o700, recursive: true });
          const info = await fs.lstat(path);
          if (!info.isDirectory()) {
            throw new Error(`Expected a directory at ${path}.`);
          }
          if (env.platform !== "win32") await fs.chmod(path, 0o700);
        },
        catch: (cause) => makeError("create-directory", path, cause),
      });

    const createConfig = Effect.gen(function* () {
      const current = yield* fileSystem
        .stat(configPath)
        .pipe(
          Effect.catchReason("PlatformError", "NotFound", () => Effect.void),
        );
      if (current === undefined || current.size === 0n) {
        yield* atomicFile.write(configPath, SCRIPT_WORKSPACE_CONFIG);
      }
    }).pipe(
      Effect.mapError((cause) => makeError("create-config", configPath, cause)),
      Effect.asVoid,
    );

    const copyTypes = Effect.gen(function* () {
      const current = yield* fileSystem
        .readFileString(typesPath)
        .pipe(
          Effect.catchReason("PlatformError", "NotFound", () => Effect.void),
        );
      if (
        current !== undefined &&
        !GENERATED_TYPES_PREFIX.startsWith(current) &&
        !current.startsWith(GENERATED_TYPES_PREFIX)
      ) {
        return;
      }
      const template = yield* fileSystem.readFile(templatePath);
      yield* atomicFile.write(typesPath, template);
    }).pipe(
      Effect.mapError((cause) => makeError("copy-types", typesPath, cause)),
    );

    return ScriptWorkspace.of({
      initialize: Effect.gen(function* () {
        yield* createDirectory(env.workspaceDir);
        yield* Effect.all(
          [
            createDirectory(scriptsDir),
            createDirectory(packagesDir),
            createPrivateDirectory(dataDir),
          ],
          { concurrency: 3, discard: true },
        );
        yield* Effect.all([createConfig, copyTypes], {
          concurrency: 2,
          discard: true,
        });
      }),
    });
  }),
);
